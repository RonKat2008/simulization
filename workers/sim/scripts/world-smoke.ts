import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createActorTransport } from 'durable-actors/backend';
import { startLocalActors, type LocalActorRuntime } from 'durable-actors/dev';
import { EventSchema, type Event } from '@simulization/shared';
const dataDir = await mkdtemp(join(tmpdir(),'sim-world-'));
const options = {project:fileURLToPath(new URL('..',import.meta.url)),entrypoint:'src/actors.ts',dataDir,quiet:true};
let rt: LocalActorRuntime | undefined;
try {
  rt = await startLocalActors(options);
  let transport = createActorTransport({projectId:rt.connection.projectId,controlPlaneUrl:rt.connection.controlPlaneUrl,apiKey:rt.connection.apiKey});
  const call = async (id:string,method:string,...args:unknown[]) => { const result = await transport.invoke('WorldActor',id,method,args); return method === 'events' ? JSON.parse(result as string) : result; };
  const status = async (id:string) => JSON.parse(await call(id,'status') as string);
  await assert.rejects(call('rollback-smoke','initialize','rollback-smoke',42,'BLIND',99,false));
  await call('rollback-smoke','initialize','rollback-smoke',42,'BLIND',6,false);
  assert.equal((await status('rollback-smoke')).seq,0);
  console.log('PASS product initialization: failed transaction then retry on same actor');
  await call('world-smoke','initialize','world-smoke',42,'BLIND',6,false);
  const initial = await status('world-smoke');
  await Promise.all([call('world-smoke','advance',initial.nextKey),call('world-smoke','advance',initial.nextKey)]);
  assert.equal((await call('world-smoke','events',0) as Event[]).filter(e=>e.type==='system').length,1,'duplicate phase applied');
  for(let i=1;i<5;i++) await call('world-smoke','advance',(await status('world-smoke')).nextKey);
  const one = await call('world-smoke','events',0) as Event[];
  assert.deepEqual([...new Set(one.map(e=>e.phase))],['negotiate','trade','act','reveal']);
  assert.equal((await status('world-smoke')).round,2);
  console.log(`PASS Terse WorldActor: one complete six-stub-agent round (${one.length} ordered events), concurrent duplicate no-op`);
  const before = await status('world-smoke');
  await rt.stop(); rt = await startLocalActors(options); transport = createActorTransport({projectId:rt.connection.projectId,controlPlaneUrl:rt.connection.controlPlaneUrl,apiKey:rt.connection.apiKey});
  assert.deepEqual(await status('world-smoke'),before);
  assert.deepEqual(await call('world-smoke','events',0),one);
  for(let i=0;i<25;i++) await call('world-smoke','advance',(await status('world-smoke')).nextKey);
  const final = await status('world-smoke'); assert.equal(final.status,'done');
  const events = await call('world-smoke','events',0) as Event[];
  events.forEach((e,i)=>{EventSchema.parse(e);assert.equal(e.seq,i+1);assert.equal(e.id,`world-smoke-${i+1}`);});
  assert.deepEqual(await call('world-smoke','events',events.length-2),events.slice(-2));
  assert.equal(Object.keys(final.finalScores).length,6);
  await call('world-smoke','stop');
  assert.deepEqual(await status('world-smoke'),final,'stop must not turn a completed run into a failure');
  console.log(`PASS Terse WorldActor: six rounds (${events.length} events), restart recovery, event cursor, final scores`);
  await call('stalled-smoke','initialize','stalled-smoke',42,'BLIND',6,false,true);
  const stalledStart = Date.now();
  for(let i=0;i<5;i++) await call('stalled-smoke','advance',(await status('stalled-smoke')).nextKey);
  assert.equal((await status('stalled-smoke')).round,2);
  assert.ok(Date.now()-stalledStart < 35000);
  const stalledEvents = await call('stalled-smoke','events',0) as Event[];
  assert.ok(stalledEvents.some(e=>e.phase==='act' && e.actorId==='merchant-01' && e.type==='pass'));
  console.log(`PASS product stalled-agent round: ${Date.now()-stalledStart}ms, 12s timeout + one retry, failed merchant passed`);
  await call('auto-smoke','initialize','auto-smoke',7,'LABELED',6,true);
  await rt.stop(); rt = await startLocalActors(options); transport = createActorTransport({projectId:rt.connection.projectId,controlPlaneUrl:rt.connection.controlPlaneUrl,apiKey:rt.connection.apiKey});
  const deadline = Date.now()+25000;
  while((await status('auto-smoke')).round===1 && Date.now()<deadline) await new Promise(r=>setTimeout(r,250));
  assert.equal((await status('auto-smoke')).round,2,'durable alarms did not resume round after restart');
  await call('auto-smoke','stop'); const stopped = await status('auto-smoke');
  await call('auto-smoke','advance',stopped.nextKey); assert.deepEqual(await status('auto-smoke'),stopped);
  console.log('PASS Terse WorldActor: alarm-driven round survives runtime restart; stop prevents advancement');
} finally { await rt?.stop(); await rm(dataDir,{recursive:true,force:true}); }
